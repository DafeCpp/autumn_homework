#pragma once

#include <cstddef>
#include <fstream>
#include <string>
#include <string_view>

namespace graph_trace {
// Записывает шаги алгоритма для просмотрщика в отдельный JSONL-файл:
// одно событие на строку. Вывод ответа программы в stdout не изменяется.
// Методы записи ничего не делают, если IsEnabled() возвращает false.
class Recorder {
 public:
  // Открывает файл из переменной окружения GRAPH_TRACE, перезаписывая его,
  // и записывает версию формата. Без пути или при ошибке открытия запись
  // отключена. Раннер назначает отдельный путь для каждого теста.
  Recorder();

  // Возвращает true, если файл открыт, ошибок записи нет и лимит не достигнут.
  bool IsEnabled() const;

  // Описывает граф: count — число вершин, directed — есть ли направления
  // у рёбер, first — номер первой вершины. Номера: first..first+count-1.
  // Вызовите один раз перед добавлением рёбер и записью шагов.
  void Graph(int count, bool directed = false, int first = 1);
  // Добавляет ребро между вершинами from и to; для ориентированного графа
  // направление — from → to. id — порядковый номер ребра во входе с нуля.
  // Кратные рёбра имеют разные id. Запишите все рёбра в порядке входа
  // до событий алгоритма; не добавляйте неориентированное ребро дважды.
  void AddEdge(int id, int from, int to);

  // Меняет состояние вершины id: "idle" — не посещена, "queued" — в очереди,
  // "active" — текущая, "done" — обработана, "cut" — точка сочленения.
  // Изменение будет видно в следующем кадре, созданном методом Step.
  void Node(int id, std::string_view state);

  // Меняет состояние ребра по id из AddEdge: "tree" — ребро дерева обхода,
  // "back" — обратное ребро DFS, "non_tree" — нетревесное ребро BFS,
  // "bridge" — мост, "idle" — обычное ребро. Изменение войдёт в следующий Step.
  // Подсветка моста сохраняет ранее записанную роль ребра в дереве обхода.
  void Edge(int id, std::string_view state);

  // Сохраняет у вершины id целочисленную переменную name со значением value,
  // например Value(v, "distance", distance[v]). Повторный вызов обновляет
  // значение. В следующем кадре оно появится в таблице состояния вершин.
  void Value(int id, std::string_view name, int value);

  // Завершает один шаг алгоритма с пояснением message. Просмотрщик покажет
  // кадр со всеми изменениями Node, Edge и Value после предыдущего Step.
  // Вызывайте в понятных точках алгоритма, например после обработки вершины.
  void Step(std::string_view message);

  // Записывает отметку нормального завершения. Сначала вызовите последний
  // Step, чтобы показать накопленные изменения. После Finish не добавляйте
  // события в эту запись. Сам файл закроется при уничтожении Recorder.
  void Finish();

 private:
  // Общая реализация Node и Edge: type выбирает вершину ("node") или ребро
  // ("edge"), а id и state задают изменяемый элемент и его состояние.
  void State(std::string_view type, int id, std::string_view state);

  // Записывает готовое JSON-событие line и перевод строки, сбрасывает буфер,
  // чтобы полные события сохранились даже при последующем падении программы.
  // При превышении 50000 событий или около 8 МиБ пишет отметку ограничения
  // и отключает дальнейшую запись, защищая от бесконечного роста файла.
  void Write(const std::string& line);

  std::ofstream stream_;
  unsigned events_ = 0;
  std::size_t bytes_ = 0;
  bool truncated_ = false;
};
}  // namespace graph_trace
